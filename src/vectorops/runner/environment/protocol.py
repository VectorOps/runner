"""Operational interface; no workflow or backend lifecycle dependencies."""

from typing import Protocol, runtime_checkable

from . import models as m
from .processes import models as processes


@runtime_checkable
class TargetEnvironment(Protocol):
    async def describe(self) -> m.EnvironmentDescription: ...

    async def stat(self, request: m.PathRequest) -> m.FileInfo: ...

    async def list_dir(self, request: m.ListRequest) -> m.ListResult: ...

    async def read_file(self, request: m.ReadRequest) -> m.ReadResult: ...

    async def read_lines(self, request: m.LineReadRequest) -> m.LineReadResult: ...

    async def write_file(self, request: m.WriteRequest) -> None: ...

    async def mkdir(self, request: m.MkdirRequest) -> None: ...

    async def remove(self, request: m.RemoveRequest) -> None: ...

    async def rename(self, request: m.RenameRequest) -> None: ...

    async def exec(self, request: processes.ExecRequest) -> processes.ProcessResult: ...

    async def poll(self, request: processes.PollRequest) -> processes.ProcessResult: ...

    async def write_stdin(self, request: processes.StdinRequest) -> None: ...

    async def kill(self, request: processes.SessionRequest) -> processes.KillResult: ...

    async def list_processes(self) -> list[processes.ProcessResult]: ...

    async def close(self) -> list[processes.KillResult]: ...
